class Scene:
 def __init__(self,name):self.name=name;self.elements=[{'type':'cameraUpdate','width':1200,'height':900,'x':-100,'y':-120}];self.n=0
 def add(self,kind,**kwargs):
  self.n+=1;e={'type':kind,'id':f'{self.name}-{self.n}','roughness':.5,'strokeColor':INK,'strokeWidth':1.5,'seed':20260920+self.n,**kwargs};self.elements.append(e);return e
 def box(self,x,y,w,h,text,color=BLUE):return self.add('rectangle',x=x,y=y,width=w,height=h,backgroundColor=color,fillStyle='solid',strokeColor=color,roundness={'type':3},label={'text':text,'fontSize':22,'fontFamily':2,'strokeColor':'#ffffff'})
 def text(self,x,y,text,size=21,color=INK,font=1):return self.add('text',x=x,y=y,text=text,fontSize=size,fontFamily=font,strokeColor=color)
 def arrow(self,x,y,dx,dy,points=None,dashed=False):return self.add('arrow',x=x,y=y,width=abs(dx),height=abs(dy),points=points or [[0,0],[dx,dy]],endArrowhead='arrow',strokeStyle='dashed' if dashed else 'solid')
 def save(self):(OUT/(self.name+'.mcp.json')).write_text(json.dumps(self.elements,indent=2))
